// Normalize weights to ensure sum = 1.0 per regime
export function normalizeWeights(models: ModelVote[]): ModelVote[] {
  const sumTrending = models.reduce((s, m) => s + m.weight_trending, 0);
  const sumRanging = models.reduce((s, m) => s + m.weight_ranging, 0);
  return models.map((m) => ({
    ...m,
    weight_trending: m.weight_trending / sumTrending,
    weight_ranging: m.weight_ranging / sumRanging,
  }));
}

